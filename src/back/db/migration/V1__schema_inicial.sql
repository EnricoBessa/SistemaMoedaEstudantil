CREATE TABLE tb_instituicao (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(255)
);

CREATE TABLE tb_professor (
    cpf           VARCHAR(255) PRIMARY KEY,
    nome          VARCHAR(255),
    email         VARCHAR(255),
    senha         VARCHAR(255),
    departamento  VARCHAR(255),
    saldo_moedas  INTEGER NOT NULL DEFAULT 1000,
    instituicao_id BIGINT REFERENCES tb_instituicao(id)
);

CREATE TABLE tb_aluno (
    cpf           VARCHAR(255) PRIMARY KEY,
    nome          VARCHAR(255),
    email         VARCHAR(255),
    senha         VARCHAR(255),
    rg            VARCHAR(255),
    endereco      VARCHAR(255),
    curso         VARCHAR(255),
    saldo_moedas  INTEGER NOT NULL DEFAULT 0,
    instituicao_id BIGINT REFERENCES tb_instituicao(id)
);

CREATE TABLE tb_empresa_parceira (
    cnpj   VARCHAR(255) PRIMARY KEY,
    nome   VARCHAR(255),
    email  VARCHAR(255),
    senha  VARCHAR(255)
);

CREATE TABLE tb_vantagem (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao     VARCHAR(255),
    foto          VARCHAR(255),
    custo_moedas  INTEGER NOT NULL DEFAULT 0,
    empresa_cnpj  VARCHAR(255) REFERENCES tb_empresa_parceira(cnpj)
);

CREATE TABLE tb_transacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade     INTEGER NOT NULL DEFAULT 0,
    motivo         VARCHAR(255),
    data           TIMESTAMP NOT NULL DEFAULT now(),
    codigo_cupom   VARCHAR(255),
    professor_cpf  VARCHAR(255) REFERENCES tb_professor(cpf),
    aluno_cpf      VARCHAR(255) REFERENCES tb_aluno(cpf),
    vantagem_id    BIGINT REFERENCES tb_vantagem(id)
);

CREATE TABLE tb_notificacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensagem      VARCHAR(255),
    lida          BOOLEAN NOT NULL DEFAULT FALSE,
    data_criacao  TIMESTAMP NOT NULL DEFAULT now(),
    aluno_cpf     VARCHAR(255) NOT NULL REFERENCES tb_aluno(cpf)
);
